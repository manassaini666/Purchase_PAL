import fs from "node:fs";
import path from "node:path";
import readline from "node:readline/promises";
import { randomUUID } from "node:crypto";
import { getAccessToken, createOrder, getOrder, captureOrder } from "../lib/paypal.ts";

// ---- load .env.local without extra packages ----
function loadEnvFile(file) {
  const full = path.join(process.cwd(), file);
  if (!fs.existsSync(full)) return false;
  for (const line of fs.readFileSync(full, "utf8").split(/\r?\n/)) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i === -1) continue;
    const key = t.slice(0, i).trim();
    let value = t.slice(i + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = value;
  }
  return true;
}

// ---- step log (this becomes docs/paypal-verified-path.md) ----
const results = [
  { key: "token", title: "Get access token", endpoint: "POST /v1/oauth2/token", status: "NOT RUN", detail: "" },
  { key: "create", title: "Create order (5.00 USD, intent CAPTURE)", endpoint: "POST /v2/checkout/orders", status: "NOT RUN", detail: "" },
  { key: "approve", title: "Buyer approval in sandbox (manual)", endpoint: "browser: payer-action link", status: "NOT RUN", detail: "" },
  { key: "statusBefore", title: "Get order status after approval", endpoint: "GET /v2/checkout/orders/{id}", status: "NOT RUN", detail: "" },
  { key: "capture", title: "Capture order", endpoint: "POST /v2/checkout/orders/{id}/capture", status: "NOT RUN", detail: "" },
  { key: "statusAfter", title: "Get order status after capture", endpoint: "GET /v2/checkout/orders/{id}", status: "NOT RUN", detail: "" },
];

function mark(key, status, detail) {
  const r = results.find((x) => x.key === key);
  r.status = status;
  r.detail = detail;
}

function describeError(e) {
  if (e && e.name === "PayPalError") {
    return `${e.message}. PayPal said: ${String(e.body).slice(0, 600)}`;
  }
  return e instanceof Error ? e.message : String(e);
}

async function runStep(key, fn) {
  try {
    return await fn();
  } catch (e) {
    mark(key, "FAILED", describeError(e));
    throw e;
  }
}

function writeDoc(orderId) {
  const esc = (s) => String(s).replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
  const lines = [
    "# PayPal Sandbox verified path",
    "",
    `Generated by \`scripts/spike.mjs\` on ${new Date().toISOString()}.`,
    `Order ID used (sandbox): ${orderId ?? "none (order was not created)"}`,
    "",
    "## What actually happened in the spike run",
    "",
    "| # | Step | Endpoint | Result | Detail |",
    "|---|------|----------|--------|--------|",
    ...results.map(
      (r, i) => `| ${i + 1} | ${esc(r.title)} | \`${esc(r.endpoint)}\` | **${r.status}** | ${esc(r.detail)} |`
    ),
    "",
    "Only steps marked OK are verified. NOT RUN and FAILED steps are not verified.",
    "The approval step is MANUAL: the script cannot see the browser, so check the status row after it.",
    "",
    "## Checked against PayPal docs (2026-11-05)",
    "",
    "- Sandbox base URL `https://api-m.sandbox.paypal.com`",
    "- `POST /v2/checkout/orders` with `intent: CAPTURE` and `payment_source.paypal.experience_context.return_url/cancel_url`; response status `PAYER_ACTION_REQUIRED` with a `payer-action` link",
    "- `POST /v2/checkout/orders/{id}/capture` with body `{}`",
    "- `GET /v2/checkout/orders/{id}`",
    "- `PayPal-Request-Id` header on create order",
    "- Orders can be captured or modified only within 3 hours of creation",
    "",
    "## NOT confirmed in docs yet (needs an official doc page)",
    "",
    "- `POST /v1/oauth2/token` with Basic auth and `grant_type=client_credentials`",
    "- `PayPal-Request-Id` header on capture",
    "- Capture response field names under `purchase_units[].payments.captures[]`",
    "- Order status being `APPROVED` after buyer approval",
    "",
  ];
  fs.mkdirSync(path.join(process.cwd(), "docs"), { recursive: true });
  fs.writeFileSync(path.join(process.cwd(), "docs", "paypal-verified-path.md"), lines.join("\n"));
  console.log("\nWrote docs/paypal-verified-path.md");
}

async function main() {
  console.log("=== Purchase Pal PayPal Sandbox spike ===\n");
  if (!loadEnvFile(".env.local")) {
    console.log("Warning: .env.local not found in this folder. Run from the project root.");
  }

  let orderId;
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });

  try {
    // 1) token
    await runStep("token", async () => {
      await getAccessToken();
      mark("token", "OK", "Access token received (not printed)");
    });
    console.log("1) Access token: OK");

    // 2) create order: 500 minor units = 5.00 USD
    const order = await runStep("create", async () => {
      const o = await createOrder({
        amountMinor: 500,
        currency: "USD",
        returnUrl: "https://example.com/paypal-return",
        cancelUrl: "https://example.com/paypal-cancel",
        requestId: randomUUID(),
      });
      mark("create", "OK", `status=${o.status}; payer-action link received`);
      return o;
    });
    orderId = order.id;
    console.log(`2) Order created. ID: ${order.id}  status: ${order.status}`);

    // 3) manual approval
    console.log("\nOpen this link in your browser and approve using your SANDBOX BUYER account:");
    console.log(order.approvalUrl);
    console.log(
      "\n(After you approve, the browser will jump to an example.com page. That is expected.)"
    );
    await rl.question("\nPress Enter here AFTER you have approved the payment... ");
    mark("approve", "MANUAL", "Link printed; user pressed Enter (approval not machine-verified)");

    // 4) status before capture
    const before = await runStep("statusBefore", async () => {
      const s = await getOrder(order.id);
      mark(
        "statusBefore",
        "OK",
        `status=${s.status}${s.status === "APPROVED" ? "" : " (expected APPROVED)"}`
      );
      return s;
    });
    console.log(`3) Status after approval: ${before.status}`);
    if (before.status !== "APPROVED") {
      console.log("   Warning: not APPROVED. Capture will probably fail. Trying anyway to learn the error.");
    }

    // 5) capture
    const cap = await runStep("capture", async () => {
      const c = await captureOrder(order.id, randomUUID());
      const first = c.captures[0];
      mark(
        "capture",
        "OK",
        `status=${c.status}; captures=${c.captures.length}` +
          (first ? `; capture id=${first.id}; capture status=${first.status}` : "")
      );
      return c;
    });
    console.log(`4) Capture: ${cap.status}${cap.captures[0] ? `  (capture id: ${cap.captures[0].id})` : ""}`);

    // 6) final status
    const after = await runStep("statusAfter", async () => {
      const s = await getOrder(order.id);
      mark("statusAfter", "OK", `status=${s.status}`);
      return s;
    });
    console.log(`5) Final order status: ${after.status}`);
  } catch (e) {
    console.error("\nSPIKE FAILED:", describeError(e));
    process.exitCode = 1;
  } finally {
    rl.close();
    writeDoc(orderId);
  }
}

main();